        )
    }

    /**
     * Orders a list of currencies so that pinned currencies appear first,
     * arranged alphabetically by country, followed by remaining currencies,
     * also arranged alphabetically by country.
     */
    fun orderCurrencies(currencies: List<Currency>, pinnedCodes: Set<String>): List<Currency> {
        val countryComparator = Comparator<Currency> { a, b ->
            val comp = a.country.compareTo(b.country, ignoreCase = true)
            if (comp != 0) comp else a.code.compareTo(b.code, ignoreCase = true)
        }
        val pinned = currencies.filter { pinnedCodes.contains(it.code) }.sortedWith(countryComparator)
        val unpinned = currencies.filter { !pinnedCodes.contains(it.code) }.sortedWith(countryComparator)
        return pinned + unpinned
    }

